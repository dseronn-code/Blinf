const asArray = <T,>(v: T | T[] | undefined): T[] => (v == null ? [] : Array.isArray(v) ? v : [v]);

export async function importNfeXml(actor: Actor, xml: string) {
  const parser = new XMLParser({ ignoreAttributes: false, attributeNamePrefix: '@', parseTagValue: false });
  let doc: any;
  try {
    doc = parser.parse(xml);
  } catch {
    fail(400, 'Arquivo XML inválido');
  }
  const nfe = doc?.nfeProc?.NFe || doc?.NFe;
  const inf = nfe?.infNFe;
  if (!inf) fail(400, 'XML não é uma NF-e válida (infNFe não encontrado)');
  const accessKey = String(inf['@Id'] || '').replace(/^NFe/, '');
  if (!isValidAccessKey(accessKey)) fail(400, `Chave de acesso inválida: ${accessKey}`);
  const company = await prisma.company.findUnique({ where: { id: actor.companyId } });
  const destCnpj = onlyDigits(inf.dest?.CNPJ || inf.dest?.CPF);
  if (destCnpj && company && destCnpj !== onlyDigits(company.cnpj)) fail(400, `Esta NF-e foi emitida para outro destinatário (CNPJ ${destCnpj})`);
  const exists = await prisma.inboundInvoice.findUnique({ where: { companyId_accessKey: { companyId: actor.companyId, accessKey } } });
  if (exists) fail(409, `NF-e ${exists.number} já importada`);

  const emitCnpj = onlyDigits(inf.emit?.CNPJ);
  let supplier = await prisma.contact.findFirst({ where: { organizationId: actor.orgId, document: { in: [emitCnpj, inf.emit?.CNPJ] } } });
  if (!supplier) {
    const e = inf.emit;
    supplier = await prisma.contact.create({
      data: {
        organizationId: actor.orgId, types: ['FORNECEDOR'], personType: 'PJ', name: e.xNome, tradeName: e.xFant || null, document: emitCnpj, ie: e.IE ? String(e.IE) : null, ieIndicator: 1,
        street: e.enderEmit?.xLgr, number: e.enderEmit?.nro ? String(e.enderEmit.nro) : null, district: e.enderEmit?.xBairro, city: e.enderEmit?.xMun, uf: e.enderEmit?.UF, zip: e.enderEmit?.CEP ? String(e.enderEmit.CEP) : null,
        notes: 'Cadastrado automaticamente na importação de XML de NF-e',
      },
    });
  }
  const dets = asArray(inf.det);
  const items = [];
  for (const d of dets) {
    const p = d.prod;
    const gtin = p.cEAN && p.cEAN !== 'SEM GTIN' ? String(p.cEAN) : null;
    const code = String(p.cProd);
    const match = await prisma.product.findFirst({ where: { organizationId: actor.orgId, OR: [...(gtin ? [{ gtin }] : []), { sku: code }] } });
    items.push({ code, description: String(p.xProd), ncm: String(p.NCM || ''), cfop: String(p.CFOP || ''), unit: String(p.uCom || 'UN'), quantity: Number(p.qCom), unitPrice: round2(Number(p.vUnCom)), total: round2(Number(p.vProd)), gtin, productId: match?.id || null });
  }
  const tot = inf.total?.ICMSTot || {};
  const duplicates = asArray(inf.cobr?.dup).map((d: any) => ({ number: String(d.nDup), dueDate: String(d.dVenc), amount: round2(Number(d.vDup)) }));
  return prisma.inboundInvoice.create({
    data: {
      companyId: actor.companyId,
      accessKey,
      number: String(inf.ide?.nNF),
      series: String(inf.ide?.serie),
      issueDate: new Date(inf.ide?.dhEmi || Date.now()),
      supplierId: supplier.id,
      supplierName: supplier.name,
      supplierCnpj: emitCnpj,
      total: round2(Number(tot.vNF || 0)),
      productsTotal: round2(Number(tot.vProd || 0)),
      freight: round2(Number(tot.vFrete || 0)),
      icmsValue: round2(Number(tot.vICMS || 0)),
      ipiValue: round2(Number(tot.vIPI || 0)),
      items,
      duplicates,
      xml,
    },
  });
}

/**
 * Lança a NF-e de entrada: vincula/cria produtos, gera pedido de compra
 * RECEBIDO e dispara as automações (estoque + contas a pagar + custo).
 */
export async function launchInbound(actor: Actor, id: string, opts: { warehouseId?: string | null; mapping?: Record<string, string>; createMissing?: boolean } = {}) {
  const inb = await prisma.inboundInvoice.findFirst({ where: { id, companyId: actor.companyId } });
  if (!inb) fail(404, 'NF-e de entrada não encontrada');
  if (inb!.status === 'LANCADA') fail(400, 'NF-e já lançada');
  const items = inb!.items as { code: string; description: string; ncm: string; unit: string; quantity: number; unitPrice: number; total: number; gtin: string | null; productId: string | null }[];
  const resolved = [];
  for (const it of items) {
    let productId = opts.mapping?.[it.code] || it.productId;
    if (!productId) {
      if (opts.createMissing === false) fail(400, `Vincule o item "${it.description}" a um produto`);
      const p = await prisma.product.create({
        data: { organizationId: actor.orgId, sku: `${it.code}`.slice(0, 40), name: it.description, ncm: it.ncm, unit: it.unit, gtin: it.gtin, costPrice: it.unitPrice, price: round2(it.unitPrice * 1.8), supplierId: inb!.supplierId },
      }).catch(async () => prisma.product.create({ data: { organizationId: actor.orgId, sku: `${it.code}-${randomDigits(3)}`, name: it.description, ncm: it.ncm, unit: it.unit, costPrice: it.unitPrice, price: round2(it.unitPrice * 1.8), supplierId: inb!.supplierId } }));
      productId = p.id;
    }
    resolved.push({ ...it, productId });
  }
  const freightAndTax = round2(inb!.total - inb!.productsTotal);
  const po = await savePurchase(actor, {
    supplierId: inb!.supplierId!,
    warehouseId: opts.warehouseId,
    items: resolved.map((r) => ({ productId: r.productId!, quantity: r.quantity, unitCost: r.unitPrice })),
    otherCosts: freightAndTax > 0 ? freightAndTax : 0,
    discount: freightAndTax < 0 ? -freightAndTax : 0,
    installments: Math.max(1, (inb!.duplicates as unknown[]).length),
    notes: `Gerado pela importação do XML da NF-e ${inb!.number} série ${inb!.series}`,
  });
  await prisma.purchaseOrder.update({ where: { id: po.id }, data: { nfeKey: inb!.accessKey, nfeNumber: inb!.number } });
  await prisma.inboundInvoice.update({ where: { id }, data: { status: 'LANCADA', purchaseOrderId: po.id, items: resolved } });
  return receivePurchase(actor, po.id);
}

/** Gera um XML de NF-e de fornecedor (para testar a importação) */
export async function sampleSupplierXml(actor: Actor) {
  const company = (await prisma.company.findUnique({ where: { id: actor.companyId } }))!;
  const supplier = await prisma.contact.findFirst({ where: { organizationId: actor.orgId, types: { has: 'FORNECEDOR' }, personType: 'PJ' } });
  const products = await prisma.product.findMany({ where: { organizationId: actor.orgId, kind: { in: ['SIMPLES', 'MATERIA_PRIMA', 'VARIACAO'] } }, take: 30 });
  const chosen = products.sort(() => Math.random() - 0.5).slice(0, 4);
  const cnpj = onlyDigits(supplier?.document) || '11222333000181';
  const number = Number(randomDigits(5));
  const now = new Date();
  const key = buildAccessKey({ uf: supplier?.uf || 'SP', date: now, cnpj, model: 55, series: 1, number });
  let vProd = 0;
  const dets = chosen.map((p, i) => {
    const q = (i + 1) * 10;
    const v = round2(p.costPrice || p.price * 0.5);
    vProd += round2(q * v);
    return `<det nItem="${i + 1}"><prod><cProd>${p.sku}</cProd><cEAN>${p.gtin || 'SEM GTIN'}</cEAN><xProd>${p.name}</xProd><NCM>${p.ncm || '61091000'}</NCM><CFOP>6102</CFOP><uCom>${p.unit}</uCom><qCom>${q.toFixed(4)}</qCom><vUnCom>${v.toFixed(10)}</vUnCom><vProd>${(q * v).toFixed(2)}</vProd></prod><imposto><ICMS><ICMS00><orig>0</orig><CST>00</CST><vBC>${(q * v).toFixed(2)}</vBC><pICMS>12.00</pICMS><vICMS>${(q * v * 0.12).toFixed(2)}</vICMS></ICMS00></ICMS></imposto></det>`;
  });
  vProd = round2(vProd);
  const freight = 45.9;
  const vNF = round2(vProd + freight);
  const half = round2(vNF / 2);
  return `<?xml version="1.0" encoding="UTF-8"?>
<nfeProc xmlns="http://www.portalfiscal.inf.br/nfe" versao="4.00"><NFe><infNFe Id="NFe${key}" versao="4.00"><ide><cUF>35</cUF><natOp>VENDA DE MERCADORIA</natOp><mod>55</mod><serie>1</serie><nNF>${number}</nNF><dhEmi>${now.toISOString()}</dhEmi><tpNF>1</tpNF></ide><emit><CNPJ>${cnpj}</CNPJ><xNome>${supplier?.name || 'FORNECEDOR EXEMPLO LTDA'}</xNome><xFant>${supplier?.tradeName || ''}</xFant><enderEmit><xLgr>${supplier?.street || 'Rua das Indústrias'}</xLgr><nro>${supplier?.number || '100'}</nro><xBairro>${supplier?.district || 'Distrito Industrial'}</xBairro><xMun>${supplier?.city || 'São Paulo'}</xMun><UF>${supplier?.uf || 'SP'}</UF><CEP>${onlyDigits(supplier?.zip) || '01000000'}</CEP></enderEmit><IE>${supplier?.ie || '123456789110'}</IE><CRT>3</CRT></emit><dest><CNPJ>${onlyDigits(company.cnpj)}</CNPJ><xNome>${company.name}</xNome></dest>${dets.join('')}<total><ICMSTot><vBC>${vProd.toFixed(2)}</vBC><vICMS>${(vProd * 0.12).toFixed(2)}</vICMS><vProd>${vProd.toFixed(2)}</vProd><vFrete>${freight.toFixed(2)}</vFrete><vIPI>0.00</vIPI><vNF>${vNF.toFixed(2)}</vNF></ICMSTot></total><cobr><fat><nFat>${number}</nFat><vOrig>${vNF.toFixed(2)}</vOrig><vLiq>${vNF.toFixed(2)}</vLiq></fat><dup><nDup>001</nDup><dVenc>${addDays(now, 30).toISOString().slice(0, 10)}</dVenc><vDup>${half.toFixed(2)}</vDup></dup><dup><nDup>002</nDup><dVenc>${addDays(now, 60).toISOString().slice(0, 10)}</dVenc><vDup>${round2(vNF - half).toFixed(2)}</vDup></dup></cobr></infNFe></NFe><protNFe versao="4.00"><infProt><chNFe>${key}</chNFe><nProt>135${randomDigits(12)}</nProt><cStat>100</cStat></infProt></protNFe></nfeProc>`;
}

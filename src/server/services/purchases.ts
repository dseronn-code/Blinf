/**
 * Compras: pedidos de compra, check-in de recebimento (conferência),
 * recebimento com entrada de estoque/contas a pagar/custo médio e
 * importação de XML de NF-e de entrada (layout 4.00).
 */
import { XMLParser } from 'fast-xml-parser';
import { prisma } from '@/lib/db';
import { addDays, round2, round3, onlyDigits, randomDigits } from '@/lib/utils';
import { buildAccessKey, isValidAccessKey } from '@/lib/br';
import { fail } from '../errors';
import { nextNumber } from '../sequence';
import { emit } from '../events';
import { moveStock } from './stock';
import { createEntries } from './finance';
import type { Actor } from './sales';

export type PurchaseInput = {
  supplierId: string;
  warehouseId?: string | null;
  date?: string;
  expectedDate?: string | null;
  items: { productId: string; quantity: number; unitCost: number; lotNumber?: string | null; expiresAt?: string | null }[];
  freight?: number;
  discount?: number;
  otherCosts?: number;
  installments?: number;
  paymentTermDays?: number;
  paymentMethod?: string;
  notes?: string | null;
  autoGenerated?: boolean;
};

export async function savePurchase(actor: Actor, input: PurchaseInput, id?: string) {
  const products = await prisma.product.findMany({ where: { id: { in: input.items.map((i) => i.productId) } } });
  const items = input.items
    .filter((i) => Number(i.quantity) > 0)
    .map((i) => {
      const p = products.find((x) => x.id === i.productId);
      if (!p) fail(400, 'Produto inválido no pedido de compra');
      const quantity = round3(Number(i.quantity));
      const unitCost = round2(Number(i.unitCost) || p!.costPrice);
      return { productId: p!.id, description: p!.name, quantity, unitCost, total: round2(quantity * unitCost), lotNumber: i.lotNumber || null, expiresAt: i.expiresAt ? new Date(i.expiresAt) : null };
    });
  if (!items.length) fail(400, 'Informe ao menos um item');
  const subtotal = round2(items.reduce((a, i) => a + i.total, 0));
  const total = round2(subtotal + (Number(input.freight) || 0) + (Number(input.otherCosts) || 0) - (Number(input.discount) || 0));
  const data = {
    supplierId: input.supplierId,
    warehouseId: input.warehouseId || null,
    date: input.date ? new Date(input.date) : new Date(),
    expectedDate: input.expectedDate ? new Date(input.expectedDate) : null,
    freight: round2(Number(input.freight) || 0),
    discount: round2(Number(input.discount) || 0),
    otherCosts: round2(Number(input.otherCosts) || 0),
    subtotal,
    total,
    installments: Math.max(1, Number(input.installments) || 1),
    paymentTermDays: Number(input.paymentTermDays ?? 30),
    paymentMethod: input.paymentMethod || 'BOLETO',
    notes: input.notes || null,
  };
  if (id) {
    const po = await prisma.purchaseOrder.findFirst({ where: { id, companyId: actor.companyId } });
    if (!po) fail(404, 'Pedido de compra não encontrado');
    if (['RECEBIDO', 'CANCELADO'].includes(po!.status)) fail(400, 'Pedido de compra já recebido/cancelado');
    await prisma.purchaseOrderItem.deleteMany({ where: { purchaseOrderId: id } });
    return prisma.purchaseOrder.update({ where: { id }, data: { ...data, items: { create: items } }, include: { items: true } });
  }
  const number = await nextNumber(prisma, actor.companyId, 'PEDIDO_COMPRA', 1);
  return prisma.purchaseOrder.create({ data: { ...data, companyId: actor.companyId, number, autoGenerated: !!input.autoGenerated, items: { create: items } }, include: { items: true } });
}

/** Check-in de recebimento: registra a conferência física item a item */
export async function checkinPurchase(actor: Actor, id: string, items: { itemId: string; checkedQty: number; lotNumber?: string | null; expiresAt?: string | null }[]) {
  const po = await prisma.purchaseOrder.findFirst({ where: { id, companyId: actor.companyId }, include: { items: true } });
  if (!po) fail(404, 'Pedido de compra não encontrado');
  if (['RECEBIDO', 'CANCELADO'].includes(po!.status)) fail(400, 'Pedido já recebido/cancelado');
  for (const it of items) {
    if (!po!.items.find((x) => x.id === it.itemId)) continue;
    await prisma.purchaseOrderItem.update({ where: { id: it.itemId }, data: { checkedQty: round3(Number(it.checkedQty) || 0), lotNumber: it.lotNumber || null, expiresAt: it.expiresAt ? new Date(it.expiresAt) : null } });
  }
  await prisma.purchaseOrder.update({ where: { id }, data: { status: 'EM_CONFERENCIA' } });
  const updated = await prisma.purchaseOrder.findUnique({ where: { id }, include: { items: true } });
  const divergences = updated!.items.filter((i) => i.checkedQty !== i.quantity).map((i) => ({ description: i.description, expected: i.quantity, checked: i.checkedQty }));
  return { purchase: updated, divergences };
}

/**
 * Recebe o pedido de compra. Se houve check-in, usa as quantidades conferidas.
 * Os efeitos (estoque, contas a pagar, custo) são aplicados pelas automações.
 */
export async function receivePurchase(actor: Actor, id: string) {
  const po = await prisma.purchaseOrder.findFirst({ where: { id, companyId: actor.companyId }, include: { items: true } });
  if (!po) fail(404, 'Pedido de compra não encontrado');
  if (po!.status === 'RECEBIDO') fail(400, 'Pedido já recebido');
  if (po!.status === 'CANCELADO') fail(400, 'Pedido cancelado');
  if (po!.status === 'EM_CONFERENCIA') {
    for (const it of po!.items) await prisma.purchaseOrderItem.update({ where: { id: it.id }, data: { quantity: it.checkedQty, total: round2(it.checkedQty * it.unitCost) } });
  }
  await prisma.purchaseOrder.update({ where: { id }, data: { status: 'RECEBIDO', receivedAt: new Date() } });
  await emit('purchase.received', { ...actor, purchaseId: id });
  return prisma.purchaseOrder.findUnique({ where: { id }, include: { items: true } });
}

export async function postPurchaseStock(actor: Actor, id: string) {
  const po = await prisma.purchaseOrder.findFirst({ where: { id, companyId: actor.companyId }, include: { items: true } });
  if (!po || po.stockPosted) return [];
  const extra = po.freight + po.otherCosts - po.discount;
  const changed: string[] = [];
  await prisma.$transaction(async (tx) => {
    for (const it of po.items) {
      if (it.quantity <= 0) continue;
      // Rateio de frete/despesas no custo unitário
      const share = po.subtotal ? (it.total / po.subtotal) * extra : 0;
      const unitCost = round2(it.unitCost + share / it.quantity);
      changed.push(...(await moveStock(tx, { companyId: actor.companyId, productId: it.productId, warehouseId: po.warehouseId, quantity: it.quantity, direction: 'IN', origin: po.nfeKey ? 'NFE_ENTRADA' : 'COMPRA', originId: po.id, originLabel: `Pedido de compra nº ${po.number}`, unitCost, lotNumber: it.lotNumber, expiresAt: it.expiresAt, userName: actor.userName })));
    }
    await tx.purchaseOrder.update({ where: { id }, data: { stockPosted: true } });
  });
  return changed;
}

export async function postPurchaseFinancial(actor: Actor, id: string) {
  const po = await prisma.purchaseOrder.findFirst({ where: { id, companyId: actor.companyId }, include: { supplier: true } });
  if (!po || po.financialPosted || po.total <= 0) return [];
  const inbound = po.nfeKey ? await prisma.inboundInvoice.findFirst({ where: { companyId: actor.companyId, accessKey: po.nfeKey } }) : null;
  const dups = ((inbound?.duplicates as { number: string; dueDate: string; amount: number }[]) || []).filter((d) => d.amount > 0);
  let created;
  if (dups.length) {
    created = [];
    for (const [i, d] of dups.entries()) {
      created.push(
        ...(await createEntries(prisma, {
          companyId: actor.companyId, type: 'PAGAR', description: `NF-e ${inbound!.number} - ${po.supplier.name} (${i + 1}/${dups.length})`, contactId: po.supplierId, contactName: po.supplier.name,
          total: d.amount, firstDueDate: new Date(d.dueDate), origin: 'NFE_ENTRADA', originId: po.id, chartAccountCode: '2.1.01', paymentMethod: 'BOLETO', documentNumber: d.number,
        })),
      );
    }
  } else {
    created = await createEntries(prisma, {
      companyId: actor.companyId, type: 'PAGAR', description: `Pedido de compra nº ${po.number} - ${po.supplier.name}`, contactId: po.supplierId, contactName: po.supplier.name,
      total: po.total, installments: po.installments, firstDueDate: addDays(po.receivedAt || new Date(), po.paymentTermDays), origin: 'COMPRA', originId: po.id,
      chartAccountCode: '2.1.01', paymentMethod: po.paymentMethod, documentNumber: po.nfeNumber || `PC${po.number}`,
    });
  }
  await prisma.purchaseOrder.update({ where: { id }, data: { financialPosted: true } });
  return created;
}

/** Atualiza o custo do produto com o custo médio ponderado dos depósitos */
export async function updateCostsFromPurchase(actor: Actor, id: string) {
  const po = await prisma.purchaseOrder.findFirst({ where: { id, companyId: actor.companyId }, include: { items: true } });
  if (!po) return [];
  const out = [];
  for (const it of po.items) {
    const bals = await prisma.stockBalance.findMany({ where: { productId: it.productId } });
    const qty = bals.reduce((a, b) => a + Math.max(b.quantity, 0), 0);
    const avg = qty ? round2(bals.reduce((a, b) => a + Math.max(b.quantity, 0) * b.avgCost, 0) / qty) : it.unitCost;
    await prisma.product.update({ where: { id: it.productId }, data: { costPrice: avg } });
    out.push({ productId: it.productId, cost: avg });
  }
  return out;
}


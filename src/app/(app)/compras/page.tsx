'use client';
import Link from 'next/link';
import { useRouter } from 'next/navigation';
import { useState } from 'react';
import { Plus } from 'lucide-react';
import { useApi, qs } from '@/lib/api';
import { PageHeader, SearchBox, Filters, DataTable, Chips } from '@/components/common/page';
import { Button } from '@/components/ui/button';
import { Badge, StatusBadge } from '@/components/ui/badge';
import { money, fmtDate } from '@/lib/utils';

export default function Purchases() {
  const router = useRouter();
  const [q, setQ] = useState('');
  const [status, setStatus] = useState('');
  const { data, isLoading } = useApi<any>(`/api/purchases${qs({ q, status })}`);
  return (
    <div>
      <PageHeader title="Pedidos de compra" description="Ao receber: entrada no estoque (com rateio de frete no custo), contas a pagar e custo médio atualizados automaticamente" actions={<><Button variant="outline" asChild><Link href="/compras/xml">Importar XML</Link></Button><Button asChild><Link href="/compras/novo"><Plus /> Novo pedido de compra</Link></Button></>} />
      <Filters>
        <SearchBox value={q} onChange={setQ} placeholder="Fornecedor ou nº" />
        <Chips value={status} onChange={setStatus} options={[{ value: '', label: 'Todos' }, { value: 'ABERTO', label: 'Em aberto' }, { value: 'ENVIADO', label: 'Enviados' }, { value: 'EM_CONFERENCIA', label: 'Em conferência' }, { value: 'RECEBIDO', label: 'Recebidos' }, { value: 'CANCELADO', label: 'Cancelados' }]} />
      </Filters>
      <DataTable loading={isLoading} rows={data?.rows} onRowClick={(r: any) => router.push(`/compras/${r.id}`)} columns={[
        { key: 'number', header: 'Nº', cell: (r: any) => <b>{r.number}</b> },
        { key: 'date', header: 'Data', cell: (r: any) => fmtDate(r.date) },
        { key: 'supplier', header: 'Fornecedor', cell: (r: any) => <div>{r.supplier.name}{r.autoGenerated && <Badge tone="purple" className="ml-2">reposição automática</Badge>}{r.nfeNumber && <Badge tone="blue" className="ml-2">NF-e {r.nfeNumber}</Badge>}</div> },
        { key: 'expectedDate', header: 'Previsão', cell: (r: any) => fmtDate(r.expectedDate) },
        { key: 'items', header: 'Itens', align: 'right', cell: (r: any) => r._count.items },
        { key: 'total', header: 'Total', align: 'right', cell: (r: any) => money(r.total) },
        { key: 'status', header: 'Situação', cell: (r: any) => <StatusBadge status={r.status} /> },
      ]} />
    </div>
  );
}
